import type { WaImageKind, WaMessage } from "@/data/whatsapp";

/**
 * Long, made-up conversation histories for the simulated WhatsApp window, oldest first, so a
 * chat can be scrolled up through weeks of messages and pictures. `m` is the owner, `t` the
 * other person, `s` a named sender in a group. `day` puts a date label above its first message.
 */
const m = (text: string, time: string, image?: WaImageKind): WaMessage => ({ from: "me", text, time, ...(image && { image }) });
const t = (text: string, time: string, image?: WaImageKind): WaMessage => ({ from: "them", text, time, ...(image && { image }) });
const s = (sender: string, text: string, time: string, image?: WaImageKind): WaMessage => ({ from: "them", sender, text, time, ...(image && { image }) });
const day = (label: string, ...messages: WaMessage[]): WaMessage[] =>
  messages.map((message, index) => (index === 0 ? { ...message, day: label } : message));

